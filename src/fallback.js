/**
 * フォールバック — Spec Step 1: 再生成2回失敗時の固定テンプレート
 * UIは絶対に落ちない。必ず5枚返す。
 * variant ごとに異なる内容を返す。
 */

export function createFallback(fact, variant = 'normal') {
  if (variant === 'alternative') return createAlternativeFallback(fact);
  if (variant === 'strong_counter') return createStrongCounterFallback(fact);
  return createNormalFallback(fact);
}

function createNormalFallback(fact) {
  const f = fact || '（入力なし）';
  return {
    ichigeki: `「${f}」→ まず一次情報を3つ集めろ。判断はそれからだ。`,
    branching: [
      `条件A：一次情報が3つ以上見つかった場合 → 攻めの判断に進む`,
      `条件B：裏付けが1〜2つの場合 → 追加調査を48時間以内に実施`,
      `条件C：裏付けゼロの場合 → 前提自体を疑い、別の仮説を立てる`,
    ],
    onepager: [
      `第1章【状況】：「${f}」という事実が提示された`,
      `第2章【問題】：この事実から導かれる問いは「本当にそうか？」「誰が得するか？」`,
      `第3章【仮説】：表面的な理解では判断を誤る可能性が高い`,
      `第4章【検証】：一次情報の収集と、反対意見の確認が必要`,
      `第5章【結論】：事実→解釈→価値の3段階で整理すること`,
      `第6章【行動】：今日中に一次情報を1つ確認し、明日の判断材料にする`,
    ],
    counter: {
      objection: `反論：「そもそもこの事実自体が不正確・偏っている可能性がある。メディアの切り取りや発信者のバイアスを考慮すべきだ」`,
      response: `処理：出典を3つ比較し、一致する部分だけを事実として採用する。不一致部分はフラグを立てて保留する。`,
    },
    next_action: `今日やること：「${f}」について一次情報源を1つ特定し、5分で読んでメモを3行書く。`,
  };
}

function createAlternativeFallback(fact) {
  const f = fact || '（入力なし）';
  return {
    ichigeki: `「${f}」→ 全員が賛成していることが一番怪しい。逆を調べろ。`,
    branching: [
      `条件A：多数派の意見に反する証拠が見つかった場合 → その証拠を軸に別の仮説を組む`,
      `条件B：反対意見が完全にゼロの場合 → 情報統制か思考停止を疑え`,
      `条件C：賛否が拮抗している場合 → 双方の「前提条件」の違いを明確にする`,
    ],
    onepager: [
      `第1章【状況】：「${f}」が多数派の見解として流通している`,
      `第2章【問題】：多数派であること自体は正しさの証拠にならない`,
      `第3章【仮説】：この事実の「受益者」と「被害者」を逆から見れば別の絵が見える`,
      `第4章【検証】：過去に多数派が間違えた事例（例：サブプライム、東電安全神話）と構造を比較`,
      `第5章【結論】：逆ポジションを1つ持つことで思考の幅が広がる`,
      `第6章【行動】：今日、この件に反対している専門家の記事を1本読む`,
    ],
    counter: {
      objection: `反論：「逆張りは目立つだけで生産性がない。少数派が正しいとは限らないし、実害がある判断をしたら誰が責任を取るのか」`,
      response: `処理：逆張りの目的は採用ではなく検証。反対仮説を立てて潰せれば元の判断が強化される。潰せなければ見落としがある。コストは30分、リターンは判断精度の向上。`,
    },
    next_action: `今日やること：「${f}」に反対する立場の記事・発言を1つ見つけ、その論拠を3行でメモする（15分以内）。`,
  };
}

function createStrongCounterFallback(fact) {
  const f = fact || '（入力なし）';
  return {
    ichigeki: `「${f}」→ お前が一番聞きたくない反論を先に潰せ。それが最強の武器になる。`,
    branching: [
      `条件A：最強の反論者が「数字」で攻めてきた場合 → こちらも数字で返す。感情論は禁止`,
      `条件B：反論者が「前例がない」で攻めてきた場合 → 類似事例を3つ用意して潰す`,
      `条件C：反論者が「リスクが大きい」で攻めてきた場合 → 「やらないリスク」を定量化して比較する`,
    ],
    onepager: [
      `第1章【状況】：「${f}」に対して、最も手強い反対者がいると想定する`,
      `第2章【問題】：反論に備えていないと、議論の場で一撃で崩される`,
      `第3章【仮説】：事前に反論を10個リストアップし、全てに回答を用意すれば負けない`,
      `第4章【検証】：裁判の弁護士は必ず相手の論点を先読みする。同じ手法をビジネスに適用`,
      `第5章【結論】：反論を「想定内」にすることが議論の勝率を決める`,
      `第6章【行動】：反論トップ3を書き出し、各反論に数字付きの反撃を1文ずつ用意する`,
    ],
    counter: {
      objection: `反論：「そもそもこの事実の出典が信頼できない。発信者に利害関係がある。データの母数が小さい。結論ありきの恣意的な解釈だ。こんなものを前提に判断を組み立てること自体が危険だ」`,
      response: `処理：(1)出典の信頼性は「誰が・いつ・何の目的で」の3点で検証する。利害関係があっても数字が一致すれば事実は事実。(2)母数の小ささは認めた上で、追加データの取得計画を提示する。(3)「結論ありき」の批判には、逆の結論を導く条件を自ら提示して、知的誠実さを示す。`,
    },
    next_action: `今日やること：「${f}」に対する反論を3つ書き出し、それぞれ1行で反撃を書く（20分以内）。`,
  };
}
